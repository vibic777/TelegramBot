        ("cats", ("кошк", "кошач", "котик")),
        ("physics", ("физик", "механик", "термодинамик", "квант", "ньютон", "гравитац", "электрич")),
        ("psychology", ("психолог", "психологи", "психотерап", "отношени", "семейн", "границ", "чувств", "эмоци")),
        ("medicine", ("медицин", "врач", "здоров", "лечени", "лекарств", "аптек", "симптом", "пациент")),
        ("mathematics", ("математ", "алгебр", "геометр", "интеграл", "уравнен", "теорем")),
        ("chemistry", ("хими", "реакц", "колб", "менделеев", "молекул", "атом", "элемент", "таблиц менделеев")),
        ("programming", ("программ", "код", "кодер", "баг", "дебаг", "питон", "python", "разработ", "алгоритм", "нейросет")),
