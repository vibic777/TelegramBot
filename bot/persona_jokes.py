PERSONA_JOKE_BANK = {
    persona: tuple((category, template.format(topic=subject))
        for category, subjects in categories.items()
        for subject in subjects.split("|")
        for template in TEMPLATES[persona])
    for persona, categories in SUBJECTS.items()
}
for _persona, _entries in PERSONA_JOKE_BANK.items():
    assert len(_entries) >= 500 and len({text for _, text in _entries}) == len(_entries), _persona


def get_persona_joke(persona: str, category: str = "general") -> str:
    entries = PERSONA_JOKE_BANK[persona]
    matching = [text for topic, text in entries if topic == category]
    return random.choice(matching or [text for _, text in entries])
